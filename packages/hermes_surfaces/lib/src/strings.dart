/// Resolved strings for one language. Obtain with [SurfacesStrings.of] (widgets) or
/// [SurfacesStrings.forLanguage] (no context, e.g. a host's own l10n object).
class SurfacesStrings {
  const SurfacesStrings._(this.languageCode, this._table);

  /// The language actually used: a registered one, or [fallbackLanguage].
  final String languageCode;
  final Map<SurfacesText, String> _table;

  static const String fallbackLanguage = 'en';

  /// One entry per language, keyed by ISO 639-1 code. Add a language by adding a map here.
  static const Map<String, Map<SurfacesText, String>> catalog = {'en': _en, 'ru': _ru};

  /// Registered language codes, English first.
  static List<String> get languages => List.unmodifiable(catalog.keys);

  /// Accepts `ru`, `ru_RU`, `ru-RU`, any case; null or unknown falls back to English.
  static SurfacesStrings forLanguage(String? code) {
    final language = code?.split(RegExp('[-_]')).first.toLowerCase() ?? fallbackLanguage;
    final table = catalog[language];
    if (table == null) return const SurfacesStrings._(fallbackLanguage, _en);
    return SurfacesStrings._(language, table);
  }

  /// Works under any MaterialApp/WidgetsApp, with or without our own delegates: only the locale
  /// the ambient [Localizations] already resolved is read.
  static SurfacesStrings of(BuildContext context) => forLanguage(Localizations.maybeLocaleOf(context)?.languageCode);

  /// The text for [key] with `{name}` placeholders replaced from [args].
  String call(SurfacesText key, [Map<String, Object?> args = const {}]) {
    final template = _table[key] ?? _en[key]!;
    if (args.isEmpty) return template;
    return template.replaceAllMapped(placeholder, (match) {
      final name = match.group(1)!;
      return args.containsKey(name) ? '${args[name]}' : match.group(0)!;
    });
  }

  /// `{name}` in a template.
  static final RegExp placeholder = RegExp(r'\{(\w+)\}');

  /// A localized text when the error carries a [key], otherwise the error's own message
  /// (server-provided or technical) unchanged.
  String describe(SurfacesText? key, String fallback) => key == null ? fallback : call(key);
}

