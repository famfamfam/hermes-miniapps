"""Fixed, isolated build of an authored React project (ADR-007 §4, ADR-006).

The author edits only a few source files. Everything that decides what is executed at build time is
fixed here: the tsconfig and vite config are generated by this module (the author cannot add
plugins), dependencies are the template's pre-installed `node_modules` (no `npm install`, no package
scripts), and the commands are `tsc --noEmit` and `vite build`. The build runs in a throw-away
directory with a minimal environment, a wall-clock limit, an output cap and, where configured, a
sandboxing command prefix such as `systemd-run -p PrivateNetwork=yes -p MemoryMax=...`.

What this does not do: prove that authored code is harmless. The WebView sandbox (CSP, sealed
network, origin-checked bridge) is what contains the running code; the checks here give the author
fast, specific feedback and keep obviously unsupported things out of the bundle.
"""
