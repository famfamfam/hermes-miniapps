SOURCE_FILE = re.compile(r"^src/[A-Za-z0-9_-]{1,40}\.(tsx|ts|css)$")
DEFINITIONS_FILE = "definitions.json"
PROTECTED_FILES = frozenset({"src/main.tsx"})  # the entry point is fixed by the template
MAX_FILE_BYTES = 64 * 1024
MAX_FILES = 40
MAX_TOTAL_BYTES = 400 * 1024
MAX_DIST_BYTES = 3 * 1024 * 1024
MAX_DIAGNOSTICS = 20

_ALLOWED_IMPORTS = ("react", "react/jsx-runtime", "react-dom", "react-dom/client", "@hermes/mobile-sdk")
# `from"x"` and `import"x"` are legal without a space, and the specifier may sit on the next line.
_IMPORT = re.compile(r"""(?:\bfrom\s*|\bimport\s*)["']([^"']+)["']""")
# The project is flat (src/<name>.ts|tsx|css), so a relative import is exactly ./name[.ext]: no `..`, no
# folders, and no `?raw` / `?url` / `?inline` / `?worker` suffix, which make Vite embed or copy a file.
_LOCAL_IMPORT = re.compile(r"^\./[A-Za-z0-9_-]{1,40}(?:\.(?:tsx?|css))?$")
_URL = re.compile(r"https?://[^\s\"'<>)]+", re.I)
_XML_NAMESPACE = "http://www.w3.org/"  # SVG/XML namespace, not a resource
_URL_OK_IN_JS = (_XML_NAMESPACE, "https://react.dev/", "https://reactjs.org/")
_CSS_URL = re.compile(r"""url\(\s*(?P<arg>[^)]*)""", re.I)
_CSS_IMAGE_SET = re.compile(r"image-set\s*\(", re.I)
_ELEMENT = re.compile(r"<\s*(?P<tag>script|iframe|object|embed|link)\b", re.I)

# (pattern, message). Matched on code lines of .ts/.tsx files (comments blanked out first).
_CODE_RULES: list[tuple[re.Pattern[str], str]] = [
    (re.compile(r"\bfetch\s*\("), "network access is not available; read data with useQueryGroup"),
    (re.compile(r"\bXMLHttpRequest\b|\bWebSocket\b|\bEventSource\b|\bsendBeacon\b"),
     "network APIs are not available in the app sandbox"),
    (re.compile(r"\bnavigator\s*\.\s*serviceWorker\b|\bimportScripts\b|\bnew\s+(?:Shared)?Worker\b"),
     "workers are not available"),
    (re.compile(r"\beval\s*\(|\bnew\s+Function\b"), "eval and new Function are blocked by the content policy"),
    (re.compile(r"\bimport\s*\("), "dynamic import() is not supported; import modules statically"),
    (re.compile(r"\bwindow\s*\.\s*open\b|\bdocument\s*\.\s*cookie\b"), "window.open and cookies are not available"),
    (re.compile(r"\b(?:window\s*\.\s*)?location\s*\.\s*(?:href|assign|replace)\b"),
     "navigate with hash links (href=\"#/path\"), not location"),
    (re.compile(r"\blocalStorage\b|\bsessionStorage\b|\bindexedDB\b"),
     "browser storage is not available; the host owns persistence"),
    (re.compile(r"dangerouslySetInnerHTML"), "dangerouslySetInnerHTML is not allowed"),
    # Vite resolves these at build time and can copy or embed any file the build host can read.
    (re.compile(r"\bimport\s*\.\s*meta\b"), "import.meta is not available in app code"),
    (re.compile(r"\brequire\s*\("), "require() is not available; import modules statically"),
]
_ELEMENT_MESSAGE = "this element is not allowed in app markup"
_IMPORT_MESSAGE = "imports must be react, @hermes/mobile-sdk or a file of this project written as './name'"


@dataclass
class Diagnostic:
    file: str
    line: int
    message: str
    severity: str = "error"
    code: str | None = None

    def as_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {"file": self.file, "line": self.line, "message": self.message, "severity": self.severity}
        if self.code:
            out["code"] = self.code
        return out


@dataclass
class BuildResult:
    ok: bool
    stage: str  # lint | types | bundle | checks | done
    diagnostics: list[Diagnostic] = field(default_factory=list)
    log: str = ""
    seconds: float = 0.0
    dist_dir: Path | None = None
    size: int = 0

    def summary(self) -> dict[str, Any]:
        errors = [d for d in self.diagnostics if d.severity == "error"]
        out: dict[str, Any] = {
            "ok": self.ok,
            "stage": self.stage,
            "seconds": round(self.seconds, 1),
            "errors": len(errors),
            "diagnostics": [d.as_dict() for d in self.diagnostics[:MAX_DIAGNOSTICS]],
        }
        if len(self.diagnostics) > MAX_DIAGNOSTICS:
            out["truncated"] = len(self.diagnostics) - MAX_DIAGNOSTICS
        if not self.ok and self.log and not errors:
            out["log"] = self.log[-1500:]
        if self.ok:
            out["bundleBytes"] = self.size
        return out


def check_writable_path(path: str) -> str:
    """Normalised relative path the author may write, or ValueError with the reason."""
    if path == DEFINITIONS_FILE:
        return path
    if path in PROTECTED_FILES:
        raise ValueError(f"{path} is fixed by the template and cannot be changed")
    if not SOURCE_FILE.match(path):
        raise ValueError(
            "path must be definitions.json or src/<name>.ts|tsx|css (letters, digits, - and _; no sub-folders)"
        )
    return path


def check_file_set(files: dict[str, str]) -> None:
    if len(files) > MAX_FILES:
        raise ValueError(f"too many files (max {MAX_FILES})")
    total = 0
    for path, content in files.items():
        size = len(content.encode("utf-8"))
        if size > MAX_FILE_BYTES:
            raise ValueError(f"{path} is larger than {MAX_FILE_BYTES // 1024} KB")
        total += size
    if total > MAX_TOTAL_BYTES:
        raise ValueError(f"project is larger than {MAX_TOTAL_BYTES // 1024} KB")


_EOL = "\r\n  "
_REGEX_PREFIX = frozenset("(,=:[!&|?{;~^")
_REGEX_KEYWORDS = frozenset("return typeof case in of delete void throw new else do yield await".split())


def _scan_quoted(text: str, i: int) -> int:
    """End of the '...' or "..." literal opening at text[i]; an unclosed one ends with its line."""
    quote, n, j = text[i], len(text), i + 1
    while j < n and text[j] not in _EOL:
        if text[j] == "\\":
            j += 2  # may step over a line break: a backslash continues a string onto the next line
            continue
        if text[j] == quote:
            return j + 1
        j += 1
    return min(j, n)


def _scan_template(text: str, i: int) -> tuple[int, bool]:
    """Scan template-literal text from i. Returns (index after the closing backtick or after `${`, opened `${`)."""
    n = len(text)
    while i < n:
        ch = text[i]
        if ch == "\\":
            i += 2
        elif ch == "`":
            return i + 1, False
        elif ch == "$" and text[i + 1 : i + 2] == "{":
            return i + 2, True
        else:
            i += 1
    return n, False


def _scan_regex(text: str, i: int) -> int:
    """End of a /regex/flags literal opening at text[i], or -1 if the line holds no closing slash."""
    n, j, in_class = len(text), i + 1, False
    while j < n and text[j] not in _EOL:
        ch = text[j]
        if ch == "\\":
            j += 2
            continue
        if ch == "[":
            in_class = True
        elif ch == "]":
            in_class = False
        elif ch == "/" and not in_class:
            j += 1
            while j < n and text[j].isalpha():
                j += 1
            return j
        j += 1
    return -1


def _regex_may_start(text: str, i: int) -> bool:
    """A `/` after an operator (or `return`, `typeof`, ...) starts a regular expression; after an operand it divides."""
    j = i - 1
    while j >= 0 and text[j] in " \t\r\n":
        j -= 1
    if j < 0 or text[j] in _REGEX_PREFIX:
        return True
    word = re.search(r"[A-Za-z_$][\w$]*$", text[max(0, j - 12) : j + 1])
    return bool(word and word.group() in _REGEX_KEYWORDS)


def _blank_comments(text: str) -> str:
    """`text` with every real comment overwritten by spaces. Line structure and everything that is not a
    comment (code, string and template literals, regular expressions) stay byte for byte as written.

    A `/*` or `//` inside a string, template or regular expression is not a comment, so it no longer hides
    the rest of the file from the lint rules. Only comments are ever blanked: a construct misread as a
    string or regex merely stays visible to the rules (at worst a false positive). Remaining ambiguity: a
    `//` in JSX text is read as a comment unless it follows a `:` (as in `https://`); tsc is the real parser.
    """
    out: list[str] = []
    i, n, depth = 0, len(text), 0
    templates: list[int] = []  # brace depth at which each open `${` hands control back to its template
    while i < n:
        c, nxt = text[i], text[i + 1 : i + 2]
        if c == "/" and nxt == "*":
            end = text.find("*/", i + 2)
            end = n if end < 0 else end + 2
            out.append("".join(ch if ch in _EOL else " " for ch in text[i:end]))
            i = end
        elif c == "/" and nxt == "/" and text[i - 1 : i] != ":":
            end = i
            while end < n and text[end] not in _EOL:
                end += 1
            out.append(" " * (end - i))
            i = end
        elif c in "'\"":
            end = _scan_quoted(text, i)
            out.append(text[i:end])
            i = end
        elif c == "`":
            end, opened = _scan_template(text, i + 1)
            out.append(text[i:end])
            i = end
            if opened:
                templates.append(depth)
                depth += 1
        elif c == "/" and _regex_may_start(text, i) and (end := _scan_regex(text, i)) >= 0:
            out.append(text[i:end])
            i = end
        else:
            out.append(c)
            i += 1
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if templates and depth == templates[-1]:
                    templates.pop()
                    end, opened = _scan_template(text, i)
                    out.append(text[i:end])
                    i = end
                    if opened:
                        templates.append(depth)
                        depth += 1
    return "".join(out)


def _import_problem(spec: str) -> str | None:
    if spec in _ALLOWED_IMPORTS or _LOCAL_IMPORT.match(spec):
        return None
    if spec[:1] in ".#/" or any(ch in spec for ch in ":?#!\\"):
        return _IMPORT_MESSAGE
    return f"package {spec!r} is not installed in this template"


def _is_type_argument(text: str, match: re.Match[str]) -> bool:
    """`Array<object>`, `Promise<object | null>`, `i < link.length`: what follows the name cannot continue
    an element tag, so this is a type argument or a comparison. A JSX element always continues with an
    attribute name or `{`, with `/`, or with `>` and a matching closing tag; none of those is excused, so
    real markup is never let through (a bare `<object>` with no closing tag is not valid JSX anyway)."""
    rest = text[match.end() :]
    after = rest.lstrip()[:1]
    if after == "" or after.isalpha() or after in "_$/{":
        return False
    if after == ">":
        return re.search(rf"</\s*{match.group('tag')}\b", rest, re.I) is None
    return True

def _lint_css(path: str, text: str) -> list[Diagnostic]:
    out: list[Diagnostic] = []
    flagged: set[int] = set()
    for n, line in enumerate(text.splitlines(), 1):
        external = [u for u in _URL.findall(line) if not u.startswith(_XML_NAMESPACE)]
        if external or re.search(r"@import\b", line, re.I):
            out.append(Diagnostic(path, n, "external resources and @import are not available; use local styles"))
            flagged.add(n)
    # url() may only carry an inline data: URI or a #fragment. A file reference makes Vite copy that file
    # into the bundle, and the build host can read more than the project.
    for match in _CSS_URL.finditer(text):
        arg = match.group("arg").strip().lstrip("\"'").strip().lower()
        n = text.count("\n", 0, match.start()) + 1
        if not arg.startswith(("data:", "#")) and n not in flagged:
            out.append(Diagnostic(path, n, "url() may only hold a data: URI or a #fragment; files are not bundled"))
            flagged.add(n)
    for match in _CSS_IMAGE_SET.finditer(text):
        n = text.count("\n", 0, match.start()) + 1
        if n not in flagged:
            out.append(Diagnostic(path, n, "image-set() is not available; use a data: URI"))
            flagged.add(n)
    return sorted(out, key=lambda d: d.line)


def lint_sources(files: dict[str, str], definitions: dict[str, Any] | None = None) -> list[Diagnostic]:
    """Fast feedback before the compiler runs. Returns diagnostics; errors fail the build."""
    out: list[Diagnostic] = []
    for path, text in sorted(files.items()):
        if path.endswith(".css"):
            out.extend(_lint_css(path, text))
            continue
        if not path.endswith((".ts", ".tsx")):
            continue
        code_text = _blank_comments(text)
        found: list[Diagnostic] = []
        for n, code in enumerate(code_text.splitlines(), 1):
            if not code.strip():
                continue
            for pattern, message in _CODE_RULES:
                if pattern.search(code):
                    found.append(Diagnostic(path, n, message))
            for url in _URL.findall(code):
                if url.startswith(_XML_NAMESPACE):
                    continue
                found.append(Diagnostic(path, n, "external URLs are not available inside the app"))
                break
        # Imports and elements are matched over the whole text: a specifier may sit on the line after
        # `from`, and `Array<\n object>` spans lines. Line numbers come from the match position.
        for match in _IMPORT.finditer(code_text):
            problem = _import_problem(match.group(1))
            if problem:
                found.append(Diagnostic(path, code_text.count("\n", 0, match.start(1)) + 1, problem))
        for match in _ELEMENT.finditer(code_text):
            if not _is_type_argument(code_text, match):
                found.append(Diagnostic(path, code_text.count("\n", 0, match.start()) + 1, _ELEMENT_MESSAGE))
        out.extend(sorted(found, key=lambda d: d.line))
    if definitions is not None:
        out.extend(_check_query_names(files, definitions))
    return out


_USE_QUERY_GROUP = re.compile(r"useQueryGroup\s*\(\s*\[(.*?)\]\s*\)", re.S)
_QUERY_NAME = re.compile(r"""\bname\s*:\s*["']([A-Za-z0-9_]+)["']""")


def _check_query_names(files: dict[str, str], definitions: dict[str, Any]) -> list[Diagnostic]:
    """Every query named in a literal useQueryGroup([...]) call must exist in definitions.json."""
    declared = set((definitions.get("queries") or {}).keys())
    out: list[Diagnostic] = []
    used: set[str] = set()
    for path, text in sorted(files.items()):
        if not path.endswith((".ts", ".tsx")):
            continue
        for match in _USE_QUERY_GROUP.finditer(text):
            base_line = text.count("\n", 0, match.start()) + 1
            for name in _QUERY_NAME.finditer(match.group(1)):
                used.add(name.group(1))
                if name.group(1) not in declared:
                    line = base_line + match.group(1).count("\n", 0, name.start())
                    out.append(Diagnostic(path, line, f"query {name.group(1)!r} is not declared in definitions.json"))
    for name in sorted(declared - used):
        out.append(
            Diagnostic(DEFINITIONS_FILE, 1, f"query {name!r} is declared but no screen uses it", severity="warning")
        )
    return out


_TSC_LINE = re.compile(r"^(?P<file>[^\s(][^(]*)\((?P<line>\d+),(?P<col>\d+)\):\s+error\s+(?P<code>TS\d+):\s+(?P<msg>.*)$")


def parse_tsc(output: str, workdir: Path) -> list[Diagnostic]:
    out: list[Diagnostic] = []
    for raw in output.splitlines():
        match = _TSC_LINE.match(raw.strip())
        if not match:
            continue
        file = match.group("file").replace("\\", "/")
        try:
            file = Path(file).resolve().relative_to(workdir.resolve()).as_posix() if Path(file).is_absolute() else file
        except ValueError:
            pass
        out.append(Diagnostic(file, int(match.group("line")), match.group("msg")[:300], code=match.group("code")))
    return out


def _clean_env(workdir: Path) -> dict[str, str]:
    keep = ("PATH", "SystemRoot", "SYSTEMROOT", "ComSpec", "PATHEXT", "LANG", "LC_ALL")
    env = {k: os.environ[k] for k in keep if k in os.environ}
    env.update({
        "NODE_OPTIONS": "--max-old-space-size=384",
        "CI": "1",
        "NO_COLOR": "1",
        "TMPDIR": str(workdir),
        "TEMP": str(workdir),
        "TMP": str(workdir),
        "HOME": str(workdir),
        "USERPROFILE": str(workdir),
        "npm_config_update_notifier": "false",
    })
    return env


class Builder:
    """Builds an authored project against one trusted template directory."""

    _lock = threading.Lock()  # one build at a time: bounds CPU and memory on a small server

    def __init__(
        self,
        template_dir: Path,
        sdk_dir: Path,
        *,
        node: str = "node",
        timeout_s: float = 120.0,
        command_prefix: list[str] | None = None,
        max_output_bytes: int = 64 * 1024,
        work_dir: Path | None = None,
    ) -> None:
        """`work_dir`: where throw-away project directories are created. By default they are made
        inside the template directory, so Node finds its `node_modules` by walking up. A server that
        keeps the template read-only passes a writable `work_dir`; each project then gets a
        `node_modules` symlink to the template's.
        """
        self.template_dir = template_dir.resolve()
        self.sdk_dir = sdk_dir.resolve()
        self.work_dir = work_dir.resolve() if work_dir else None
        self.node = node
        self.timeout_s = timeout_s
        self.command_prefix = command_prefix or []
        self.max_output_bytes = max_output_bytes
        _warn_if_unit_outlives_client(self.command_prefix)
        self._tsc = self.template_dir / "node_modules" / "typescript" / "bin" / "tsc"
        self._vite = self.template_dir / "node_modules" / "vite" / "bin" / "vite.js"

    def available(self) -> str | None:
        """Reason the builder cannot run, or None."""
        if not (self.template_dir / "node_modules").is_dir():
            return "template dependencies are not installed (run `npm ci` in the template)"
        if not self._tsc.is_file() or not self._vite.is_file():
            return "template dependencies are incomplete"
        if not (self.sdk_dir / "index.ts").is_file():
            return "mobile SDK sources not found"
        return None

    # -- project assembly ------------------------------------------------------

    def _write_project(self, workdir: Path, files: dict[str, str]) -> None:
        sdk = self.sdk_dir.as_posix()
        types = (self.template_dir / "node_modules" / "@types" / "react").as_posix()
        (workdir / "src").mkdir(parents=True)
        if self.work_dir is not None:
            os.symlink(self.template_dir / "node_modules", workdir / "node_modules", target_is_directory=True)
        for rel, content in files.items():
            if rel == DEFINITIONS_FILE:
                continue
            (workdir / rel).write_text(content, encoding="utf-8", newline="\n")
        main = self.template_dir / "src" / "main.tsx"
        (workdir / "src" / "main.tsx").write_text(main.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
        (workdir / "index.html").write_text(
            (self.template_dir / "index.html").read_text(encoding="utf-8"), encoding="utf-8", newline="\n"
        )
        (workdir / "tsconfig.json").write_text(json.dumps({
            "compilerOptions": {
                "target": "ES2022", "lib": ["ES2022", "DOM", "DOM.Iterable"], "module": "ESNext",
                "moduleResolution": "bundler", "jsx": "react-jsx", "strict": True, "noUnusedLocals": True,
                "noUnusedParameters": True, "noFallthroughCasesInSwitch": True, "skipLibCheck": True,
                "isolatedModules": True, "noEmit": True, "types": ["vite/client"], "baseUrl": ".",
                "paths": {
                    "@hermes/mobile-sdk": [f"{sdk}/index.ts"],
                    "react": [types], "react/*": [f"{types}/*"],
                },
            },
            "include": ["src", sdk],
        }, indent=2), encoding="utf-8")
        (workdir / "vite.config.mjs").write_text(
            'import react from "@vitejs/plugin-react";\n'
            'import { defineConfig } from "vite";\n'
            "export default defineConfig({\n"
            f"  root: {json.dumps(workdir.as_posix())},\n"
            '  base: "./",\n'
            "  plugins: [react()],\n"
            f"  cacheDir: {json.dumps((workdir / '.cache').as_posix())},\n"
            f'  resolve: {{ dedupe: ["react", "react-dom"], alias: {{ "@hermes/mobile-sdk": {json.dumps(sdk + "/index.ts")} }} }},\n'
            '  build: { outDir: "dist", emptyOutDir: true, sourcemap: false, modulePreload: { polyfill: false },\n'
            "           assetsInlineLimit: 0, chunkSizeWarningLimit: 600 },\n"
            "});\n",
            encoding="utf-8",
        )

    # -- execution -------------------------------------------------------------

    def _run(self, args: list[str], workdir: Path) -> tuple[int, str]:
        command = [*self.command_prefix, self.node, *args]
        started = time.monotonic()
        try:
            proc = subprocess.Popen(
                command, cwd=workdir, env=_clean_env(workdir), stdin=subprocess.DEVNULL,
                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, **_session_kwargs(),
            )
        except OSError as exc:
            return 127, f"cannot start the build tool: {exc}"
        chunks: list[bytes] = []
        size = 0

        def pump() -> None:
            nonlocal size
            assert proc.stdout is not None
            for block in iter(lambda: proc.stdout.read(4096), b""):
                if size < self.max_output_bytes:
                    chunks.append(block)
                    size += len(block)

        reader = threading.Thread(target=pump, daemon=True)
        reader.start()
        try:
            # A tiny floor only keeps the argument positive; a short configured limit must really apply.
            proc.wait(timeout=max(0.01, self.timeout_s - (time.monotonic() - started)))
        except subprocess.TimeoutExpired:
            _kill_tree(proc)
            reader.join(timeout=2)
            return 124, "build exceeded the time limit"
        reader.join(timeout=5)
        return proc.returncode, b"".join(chunks).decode("utf-8", errors="replace")

    def build(self, files: dict[str, str], definitions: dict[str, Any] | None, out_dir: Path) -> BuildResult:
        """Build `files` (path -> text). On success the bundle input is left in `out_dir`."""
        started = time.monotonic()
        problem = self.available()
        if problem:
            return BuildResult(False, "setup", log=problem)
        try:
            check_file_set(files)
        except ValueError as exc:
            return BuildResult(False, "lint", [Diagnostic("-", 0, str(exc))])
        found = lint_sources({p: t for p, t in files.items() if p != DEFINITIONS_FILE}, definitions)
        errors = [d for d in found if d.severity == "error"]
        if errors:
            return BuildResult(False, "lint", found, seconds=time.monotonic() - started)
        if "src/App.tsx" not in files:
            return BuildResult(False, "lint", [Diagnostic("src/App.tsx", 1, "src/App.tsx is required")])

        with self._lock:
            work_root = self.work_dir or (self.template_dir / ".work")
            work_root.mkdir(parents=True, exist_ok=True)
            workdir = work_root / uuid.uuid4().hex[:12]
            try:
                self._write_project(workdir, files)
                code, output = self._run([str(self._tsc), "--noEmit", "-p", "tsconfig.json"], workdir)
                if code != 0:
                    diag = parse_tsc(output, workdir) or [Diagnostic("-", 0, output.strip()[-400:] or "type check failed")]
                    return BuildResult(False, "types", found + diag, output, time.monotonic() - started)
                # `native`: Node imports the (plain .mjs) config itself. The default loader bundles it
                # into a temp file under node_modules, which is read-only on a server.
                code, output = self._run(
                    [str(self._vite), "build", "--config", "vite.config.mjs", "--configLoader", "native"], workdir
                )
                dist = workdir / "dist"
                if code != 0 or not (dist / "index.html").is_file():
                    return BuildResult(False, "bundle", found, output, time.monotonic() - started)
                post = self._check_dist(dist)
                if any(d.severity == "error" for d in post):
                    return BuildResult(False, "checks", found + post, output, time.monotonic() - started)
                if out_dir.exists():
                    shutil.rmtree(out_dir)
                out_dir.parent.mkdir(parents=True, exist_ok=True)
                shutil.copytree(dist, out_dir)
                size = sum(p.stat().st_size for p in out_dir.rglob("*") if p.is_file())
                return BuildResult(True, "done", found + post, output, time.monotonic() - started, out_dir, size)
            finally:
                shutil.rmtree(workdir, ignore_errors=True)

    @staticmethod
    def _check_dist(dist: Path) -> list[Diagnostic]:
        out: list[Diagnostic] = []
        total = 0
        for path in sorted(p for p in dist.rglob("*") if p.is_file()):
            rel = path.relative_to(dist).as_posix()
            total += path.stat().st_size
            if path.suffix not in (".html", ".css", ".js"):
                # Assets are never inlined (assetsInlineLimit 0), so a file Vite copied in from outside the
                # project (a `new URL(...)` or CSS reference that got past the source lint) shows up here.
                out.append(Diagnostic(rel, 0, "unexpected file in build output: only .html, .js and .css are bundled"))
                continue
            text = path.read_text(encoding="utf-8", errors="replace")
            for url in _URL.findall(text):
                if path.suffix == ".js" and url.startswith(_URL_OK_IN_JS):
                    continue
                if path.suffix == ".css" and url.startswith(_XML_NAMESPACE):  # xmlns inside a data: URI
                    continue
                severity = "warning" if path.suffix == ".js" else "error"
                out.append(Diagnostic(rel, 0, f"external URL in build output: {url[:80]}", severity))
                break
        if total > MAX_DIST_BYTES:
            out.append(Diagnostic("-", 0, f"bundle is {total // 1024} KB, limit is {MAX_DIST_BYTES // 1024} KB"))
        return out


def _session_kwargs(platform: str = sys.platform) -> dict[str, Any]:
    """Popen options that put the build in its own process group (POSIX), so one signal reaches node,
    vite's helpers and a wrapping client such as `systemd-run --pipe`. Windows is handled by taskkill /T."""
    return {} if platform == "win32" else {"start_new_session": True}


def _kill_tree(proc: subprocess.Popen[bytes], platform: str = sys.platform) -> None:
    try:
        if platform == "win32":
            subprocess.run(["taskkill", "/F", "/T", "/PID", str(proc.pid)], capture_output=True, timeout=10)
        else:
            try:
                os.killpg(proc.pid, signal.SIGKILL)  # the group leader's pid is the group id (see _session_kwargs)
            except (ProcessLookupError, PermissionError):
                proc.kill()
    except Exception:
        proc.kill()
    proc.wait(timeout=5)


def _warn_if_unit_outlives_client(prefix: list[str]) -> None:
    """`systemd-run --pipe --wait` runs the build in a transient unit that is not part of our process
    group: killing the client on a timeout leaves the unit running. RuntimeMaxSec makes systemd stop it."""
    if prefix and Path(prefix[0]).name == "systemd-run" and not any("RuntimeMaxSec" in part for part in prefix):
        logging.getLogger(__name__).warning(
            "build prefix runs systemd-run without RuntimeMaxSec=: a build that exceeds the time limit stops "
            "the client but not the unit. Add `-p RuntimeMaxSec=<seconds>` (a little above the build timeout)."
        )
