"""Installer: command line surface, entry points, and a real process running `plan` on this machine."""
from __future__ import annotations

import os
import re
import subprocess
import sys

import pytest
from install_support import CHECKOUT, new_world

import ms_admin
from mobile_surfaces.install import cli
from mobile_surfaces.install.cli import build_parser, main
from mobile_surfaces.install.model import Exit

PLUGIN = CHECKOUT / "plugin"


def test_help_documents_the_commands_and_every_exit_code(capsys):
    with pytest.raises(SystemExit) as exc:
        main(["--help"])
    assert exc.value.code == 0
    text = capsys.readouterr().out
    for command in ("plan", "apply", "status", "uninstall"):
        assert re.search(rf"^\s+{command}\s", text, re.M), command
    for code, meaning in ((0, "ok"), (1, "a step failed"), (2, "bad command line"), (3, "refused"), (4, "not installed"), (5, "installed but degraded")):
        assert f"{code} {meaning}" in text
    assert "never edits Hermes' own files unless --write-hermes-config" in text


def test_exit_codes_are_stable():
    assert {e.name: int(e) for e in Exit} == {"OK": 0, "FAILED": 1, "USAGE": 2, "REFUSED": 3, "NOT_INSTALLED": 4, "DEGRADED": 5}


def test_no_option_takes_a_secret_on_the_command_line():
    """Arguments show up in `ps` and shell history: tokens are generated by the installer and read from files."""
    options = [s for action in build_parser()._actions for s in action.option_strings]
    forbidden = re.compile(r"(?:^|-)(?:token|key|password|secret|credential)s?$")
    allowed = {"--rotate-tokens", "--print-token-path", "--hermes-token-mode"}
    assert [o for o in options if forbidden.search(o) and o not in allowed] == []


def test_every_option_is_documented():
    for action in build_parser()._actions:
        if action.option_strings:
            assert action.help, action.option_strings


def test_defaults_are_the_safe_ones():
    args = build_parser().parse_args([])
    assert args.command == "plan"
    assert args.host is None and args.authoring is None and args.limits is None
    assert not args.start and not args.enable and not args.upgrade and not args.write_hermes_config
    assert not args.rotate_tokens and not args.purge and not args.reuse_data


def test_defaults_resolve_to_loopback_and_no_side_effects(tmp_path):
    w = new_world(tmp_path)
    opts = cli.resolve_options(build_parser().parse_args(["plan", "--scope", "system"]), w.deps)
    assert opts.host == "127.0.0.1" and opts.loopback_only and (opts.api_port, opts.mcp_port) == (8787, 8788)
    assert not opts.authoring and not opts.start and not opts.enable and not opts.write_hermes_config
    assert opts.limits is None and not opts.upgrade and not opts.purge


def test_source_can_point_at_another_checkout(tmp_path):
    w = new_world(tmp_path)
    other = tmp_path / "other-clone"
    (other / "plugin").mkdir(parents=True)
    assert main(["plan", "--scope", "system", "--source", str(other)], deps=w.deps) == 3
    assert "not found in" in w.cap.stdout and str(other.resolve()) in w.cap.stdout


def test_ms_admin_install_delegates_to_the_installer(monkeypatch):
    seen = []
    monkeypatch.setattr(cli, "main", lambda argv=None, **kw: seen.append(list(argv)) or 42)
    assert ms_admin.main(["install", "plan", "--scope", "user"]) == 42
    assert seen == [["plan", "--scope", "user"]]


def test_ms_admin_still_works_for_everything_else(tmp_path, capsys):
    assert ms_admin.main(["--home", str(tmp_path), "list"]) == 0
    assert capsys.readouterr().out.strip() == "[]"
    with pytest.raises(SystemExit) as exc:
        ms_admin.main(["--help"])
    assert exc.value.code == 0
    assert "install" in capsys.readouterr().out


def run_process(args, cwd, env_extra=None):
    env = {k: v for k, v in os.environ.items() if not k.startswith(("MS_", "HERMES"))}
    env.update(env_extra or {})
    return subprocess.run([sys.executable, *args], cwd=cwd, env=env, capture_output=True, text=True, timeout=120, stdin=subprocess.DEVNULL)


def test_python_dash_m_runs_a_real_plan_with_the_standard_library_only(tmp_path):
    result = run_process(["-m", "mobile_surfaces.install", "plan", "--scope", "user"], cwd=PLUGIN, env_extra={"HOME": str(tmp_path)})
    assert result.returncode == 0, result.stderr
    assert result.stdout.startswith("PLAN: install 'hermes-surfaces'. Nothing is written.")
    assert "mobile_surfaces.install" in result.stdout or "Hermes configuration" in result.stdout
    assert result.stderr == ""


def test_the_clone_wrapper_runs_from_any_directory(tmp_path):
    wrapper = CHECKOUT / "tools" / "install" / "install.py"
    result = run_process([str(wrapper), "plan", "--scope", "user", "--with-authoring"], cwd=tmp_path)
    assert result.returncode == 0, result.stderr
    assert "PLAN: install" in result.stdout and "templates/starter-app" in result.stdout


def test_ms_admin_install_runs_as_a_real_process(tmp_path):
    result = run_process(["ms_admin.py", "install", "plan", "--scope", "user", "--limits", "small"], cwd=PLUGIN)
    assert result.returncode == 0, result.stderr
    assert "MemoryMax=192M" in result.stdout


def test_the_real_plan_does_not_modify_the_checkout():
    before = sorted(str(p.relative_to(CHECKOUT)) for p in (CHECKOUT / "plugin").rglob("*") if "__pycache__" not in p.parts and ".pytest_cache" not in p.parts)
    result = run_process(["-m", "mobile_surfaces.install", "plan", "--scope", "user", "--with-authoring"], cwd=PLUGIN)
    assert result.returncode == 0
    after = sorted(str(p.relative_to(CHECKOUT)) for p in (CHECKOUT / "plugin").rglob("*") if "__pycache__" not in p.parts and ".pytest_cache" not in p.parts)
    assert before == after


SMOKE = CHECKOUT / "tools" / "install" / "smoke_linux.py"


def test_the_linux_smoke_script_documents_itself_everywhere():
    result = run_process([str(SMOKE), "--help"], cwd=CHECKOUT)
    assert result.returncode == 0 and "REAL Linux host" in result.stdout and "--scope" in result.stdout


@pytest.mark.skipif(sys.platform.startswith("linux"), reason="on Linux the script would really install something")
def test_the_linux_smoke_script_does_nothing_off_linux():
    result = run_process([str(SMOKE)], cwd=CHECKOUT)
    assert result.returncode == 2 and "needs a Linux host" in result.stderr and result.stdout == ""


def test_a_usage_error_in_a_real_process_exits_2():
    result = run_process(["-m", "mobile_surfaces.install", "frobnicate"], cwd=PLUGIN)
    assert result.returncode == 2 and "invalid choice" in result.stderr


def test_the_installer_modules_import_only_the_standard_library():
    """It must run before any dependency exists: no fastapi, uvicorn, mcp, pydantic, yaml at import time."""
    code = (
        "import sys, mobile_surfaces.install.cli, mobile_surfaces.install.hermes;"
        "bad = [m for m in ('fastapi', 'uvicorn', 'mcp', 'pydantic', 'starlette', 'yaml') if m in sys.modules];"
        "print(bad); raise SystemExit(1 if bad else 0)"
    )
    result = run_process(["-c", code], cwd=PLUGIN)
    assert result.returncode == 0, result.stdout + result.stderr


